CREATE TABLE folders (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    parent_id  BIGINT,
    name       VARCHAR(255) NOT NULL,
    deleted    BOOLEAN      NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMP,
    created_at TIMESTAMP    NOT NULL,
    updated_at TIMESTAMP    NOT NULL
);
CREATE INDEX idx_folders_owner_parent ON folders (user_id, parent_id, deleted);
CREATE INDEX idx_folders_owner_name ON folders (user_id, name);

CREATE TABLE blobs (
    sha256      VARCHAR(64)  PRIMARY KEY,
    size        BIGINT       NOT NULL,
    storage_key VARCHAR(255) NOT NULL,
    ref_count   INT          NOT NULL DEFAULT 0,
    created_at  TIMESTAMP    NOT NULL
);

CREATE TABLE files (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL,
    folder_id        BIGINT,
    name             VARCHAR(255) NOT NULL,
    ext              VARCHAR(32),
    mime_type        VARCHAR(128),
    size             BIGINT       NOT NULL DEFAULT 0,
    sha256           VARCHAR(64),
    current_version  INT          NOT NULL DEFAULT 0,
    favorite         BOOLEAN      NOT NULL DEFAULT FALSE,
    deleted          BOOLEAN      NOT NULL DEFAULT FALSE,
    deleted_at       TIMESTAMP,
    last_accessed_at TIMESTAMP,
    created_at       TIMESTAMP    NOT NULL,
    updated_at       TIMESTAMP    NOT NULL
);
CREATE INDEX idx_files_owner_folder ON files (user_id, folder_id, deleted);
CREATE INDEX idx_files_owner_name ON files (user_id, name);
CREATE INDEX idx_files_sha ON files (sha256);
CREATE INDEX idx_files_deleted ON files (deleted, deleted_at);
CREATE INDEX idx_files_owner_fav ON files (user_id, favorite, deleted);

CREATE TABLE file_versions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id     BIGINT       NOT NULL,
    version_no  INT          NOT NULL,
    sha256      VARCHAR(64)  NOT NULL,
    size        BIGINT       NOT NULL,
    mime_type   VARCHAR(128),
    note        VARCHAR(255),
    created_by  BIGINT,
    created_at  TIMESTAMP    NOT NULL,
    CONSTRAINT uk_versions_file_no UNIQUE (file_id, version_no)
);
CREATE INDEX idx_versions_sha ON file_versions (sha256);
