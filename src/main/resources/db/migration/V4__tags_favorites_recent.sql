CREATE TABLE tags (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    name       VARCHAR(64)  NOT NULL,
    color      VARCHAR(16),
    created_at TIMESTAMP    NOT NULL,
    CONSTRAINT uk_tags_owner_name UNIQUE (user_id, name)
);

CREATE TABLE file_tags (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id BIGINT NOT NULL,
    tag_id  BIGINT NOT NULL,
    CONSTRAINT uk_file_tags UNIQUE (file_id, tag_id)
);
CREATE INDEX idx_ft_tag ON file_tags (tag_id);

CREATE TABLE recent_access (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT    NOT NULL,
    file_id     BIGINT    NOT NULL,
    accessed_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_recent UNIQUE (user_id, file_id)
);
CREATE INDEX idx_recent_time ON recent_access (user_id, accessed_at);
