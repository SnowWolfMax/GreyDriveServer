CREATE TABLE upload_sessions (
    id             VARCHAR(32)  PRIMARY KEY,
    user_id        BIGINT       NOT NULL,
    folder_id      BIGINT,
    target_file_id BIGINT,
    file_name      VARCHAR(255) NOT NULL,
    total_size     BIGINT       NOT NULL,
    sha256         VARCHAR(64),
    chunk_size     INT          NOT NULL,
    total_chunks   INT          NOT NULL,
    status         VARCHAR(16)  NOT NULL,
    created_at     TIMESTAMP    NOT NULL,
    expires_at     TIMESTAMP    NOT NULL
);
CREATE INDEX idx_upload_user_status ON upload_sessions (user_id, status);
CREATE INDEX idx_upload_expire ON upload_sessions (status, expires_at);

CREATE TABLE upload_chunks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    upload_id   VARCHAR(32) NOT NULL,
    chunk_index INT         NOT NULL,
    size        BIGINT      NOT NULL,
    sha256      VARCHAR(64),
    created_at  TIMESTAMP   NOT NULL,
    CONSTRAINT uk_chunk UNIQUE (upload_id, chunk_index)
);
